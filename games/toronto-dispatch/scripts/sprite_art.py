def car_zone(taxi=False):
    hl, hw = 7.0, 4.0

    def zone(f, s):
        a = abs(s)
        if (hl * 0.30 < abs(f) < hl * 0.62) and hw - 0.2 < a < hw + 0.7:
            return 3
        if abs(f) > hl or a > hw:
            return 0
        if f > hl - 1.4 and hw - 2.3 < a < hw - 0.6:
            return 1
        if hl * 0.22 < f < hl * 0.62 and a < hw - 1.3:
            return 1
        if -hl * 0.72 < f < -hl * 0.45 and a < hw - 1.3:
            return 1
        if taxi and abs(f) < 1.0 and a < 1.4:
            return 1
        if (abs(f - hl * 0.22) < 0.5 or abs(f + hl * 0.45) < 0.5) and a < hw - 1.3:
            return 3
        return 2
    return zone


def car_frames(taxi=False):
    east = grid(TAXI_E if taxi else CAR_E)
    return eight_headings(east, transpose(east), raster(car_zone(taxi), 45))


