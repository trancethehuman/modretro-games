def moto_zone(length=11.0, rider=2.3):
    hl = length / 2

    def zone(f, s):
        a = abs(s)
        if abs(f) > hl or a > 3.0:
            return 0
        if a <= 1.0 and (f > hl - 2.3 or f < -hl + 2.3):
            return 3
        if abs(f - (hl - 3.0)) < 0.6 and a < 2.9:
            return 3
        if (f + 0.4) ** 2 + s * s < rider * rider:
            return 1 if f * f + s * s < 1.3 else 2
        if a <= 1.4:
            return 2
        return 0
    return zone


